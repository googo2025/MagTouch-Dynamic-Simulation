class R373LiveAlgorithmPanel(_PreviousPanel):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        for widget in self.grid_slaves(row=14, column=0):
            if isinstance(widget, core.ttk.Label):
                widget.configure(text=('R373：原数据充分训练XY＋Z增量；保留浅压状态、磁定位许可、'
                    '慢记忆与Z保护。旧R348模式仍可选择。本次请启用R373，重新采无载B0，'
                    '运行R373源侧／目标侧计划；不加旧门控、显示滤波或五点输出对齐。'))

    def restore(self, config):
        self.available_presets[PRESET_NAME] = registry.PROFILE_KEY
        result = super().restore(config)
        if self.vars['preset'].get() == PRESET_NAME:
            self.vars['jump_policy'].set(GATE_NAME)
        elif self.vars['jump_policy'].get() == GATE_NAME:
            self.vars['jump_policy'].set(JUMP_FAST)
        return result

    def preset_defaults(self):
        if self.vars['preset'].get() != PRESET_NAME:
            if self.vars['jump_policy'].get() == GATE_NAME:
                self.vars['jump_policy'].set(JUMP_FAST)
            return super().preset_defaults()
        profile = registry.load_profile(registry.R92_PROFILE_PATH, registry.PROFILE_KEY)
        for key in ('threshold', 'min_cosine', 'smoothing_ms'):
            self.vars[key].set(str(profile['defaults'][key]))
        self.vars['contact_threshold'].set('70')  # inherited, inactive scaffold
        self.vars['jump_policy'].set(GATE_NAME)

    def update_states(self):
        super().update_states()
        if self.vars['preset'].get() == PRESET_NAME:
            # Rendering runs every 250 ms. Writing even an identical StringVar
            # value fires changed(), which clears the operator confirmation,
            # loaded model and B0. Defaults belong to preset_defaults/restore;
            # this refresh must only configure widgets, never rewrite settings.
            self.widgets['jump_policy'].configure(values=(GATE_NAME,))
            for key in ('threshold', 'contact_threshold', 'min_cosine', 'smoothing_ms', 'jump_policy'):
                self.widgets[key].configure(state='disabled')

    def load_fit(self):
        if self.vars['preset'].get() != PRESET_NAME:
            return super().load_fit()
        if self.vars['jump_policy'].get() != GATE_NAME:
            core.messagebox.showerror('R373模式冲突', '请选择R373独立状态＋磁定位证据模式')
            return None
        predictor = super().load_fit()
        if predictor is not None:
            self.host.live_predict_state_var.set('R373充分训练模型已载入：'+predictor.model_summary)
            self.host.live_predict_baseline_var.set('无载时采B0，先观察空载，再载入并执行R373完整计划。')
        return predictor


def validate_r373_plan_row(host, item):
    if item.get('paper_protocol_r373') != 'plateau_trained_online_v1':
        return
    if item.get('paper_protocol_r348') or item.get('system_protocol_r332'):
        raise ValueError('R373新权重计划不能伪装成旧模型实验')
    frozen_components()  # check current on-disk weights before every Trial motion
    with host.live_predict_lock:
        predictor, enabled = host.live_predictor, bool(host.live_predict_enabled)
    if not enabled or type(predictor) is not LiveRetrainedPredictorR373:
        raise ValueError('R373计划要求已载入并启用R373充分训练模型')
    m = predictor.metadata
    checks = {
        'required_r372_xy_freeze_sha256': m.get('r372_xy_freeze_sha256'),
        'required_r372_z_freeze_sha256': m.get('r372_z_freeze_sha256'),
        'required_z_increment_artifact_sha256': m.get('depth_increment_artifact_sha256'),
        'required_localization_permission_sha256': m.get('localization_permission_protocol', {}).get('sha256'),
    }
    if m.get('contact_gate') != GATE_NAME or m.get('legacy_gate_applied'):
        raise ValueError('R373计划不能混用旧接触/释放门控')
    for key, actual in checks.items():
        if not item.get(key) or item[key] != actual:
            raise ValueError('R373模型或定位许可SHA不一致：'+key)
    if not item.get('record_live_predictions') or not item.get('requires_dynamic_b0'):
        raise ValueError('R373计划必须保存在线预测并逐Trial采B0')


